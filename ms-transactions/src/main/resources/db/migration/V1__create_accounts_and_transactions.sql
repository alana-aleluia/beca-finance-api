CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE CHECK (user_id > 0),
    mock_account_id VARCHAR(100) NOT NULL UNIQUE,
    initial_balance NUMERIC(19,2) NOT NULL CHECK (initial_balance >= 0),
    balance NUMERIC(19,2) NOT NULL CHECK (balance >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id, user_id)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type = 'PURCHASE'),
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'BRL'),
    amount_brl NUMERIC(19,2) NOT NULL CHECK (amount_brl = amount),
    category VARCHAR(100) NOT NULL CHECK (length(trim(category)) > 0),
    purchase_limit NUMERIC(19,2) NOT NULL CHECK (purchase_limit >= 0),
    balance_before NUMERIC(19,2) NOT NULL CHECK (balance_before >= 0),
    balance_after NUMERIC(19,2) NOT NULL CHECK (balance_after >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('APPROVED', 'REJECTED')),
    rejection_reason VARCHAR(40),
    created_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (account_id, user_id) REFERENCES accounts(id, user_id),
    CHECK ((status = 'APPROVED' AND rejection_reason IS NULL AND balance_after = balance_before - amount_brl)
        OR (status = 'REJECTED' AND rejection_reason IS NOT NULL
            AND rejection_reason IN ('INSUFFICIENT_BALANCE', 'PURCHASE_LIMIT_EXCEEDED')
            AND balance_after = balance_before))
);
CREATE INDEX transactions_owner_id ON transactions(user_id, id);
